"""
Tile geometry for sequential masked tiled refinement.

Everything is computed in LATENT CELLS, not pixels. A VAE compresses space by
some factor (32x for LTX, 8x for most image models, others differ), so a mask
boundary that isn't a multiple of that factor lands mid-cell and gets rounded
by the resampler -- exactly the hard edge tiling is trying to avoid. Working in
cells makes misalignment unrepresentable, whatever the factor is.

The core idea
-------------
Each tile is a full training-distribution generation. A context border of B
cells on each inner edge is NOT denoised; it carries already-refined pixels
from neighbouring tiles that ran earlier, so each tile is conditioned on
refined content rather than on the blurry upscale.

The generated (masked) region of tile i starts exactly where tile i-1's
generated region ended. That guarantees:
  * no gaps        - every cell is generated by some tile
  * no double-gen  - no cell is generated by two tiles

The second property matters more than it looks. A naive "border = B on every
inner edge" rule breaks on the final row/column, which is clamped flush to the
frame edge and therefore overlaps its neighbour by more than the stride. Those
cells get fully generated twice and come out visibly over-sharpened. Deriving
the mask from the neighbour's actual coverage fixes it automatically -- the
final tile simply gets a wider border.
"""

# Defaults are LTX's (32x spatial, 8x temporal). Nothing else in this module
# assumes them -- pass `cell` / `temporal` for any other latent model. Working
# in cells rather than pixels is what makes misalignment unrepresentable, and
# that argument holds whatever the compression factor happens to be.
DEFAULT_CELL = 32
DEFAULT_TEMPORAL = 8

# back-compat alias; prefer DEFAULT_CELL
VAE_SPATIAL = DEFAULT_CELL
VAE_TEMPORAL = DEFAULT_TEMPORAL


class GeometryError(ValueError):
    pass


def _axis_positions(total, tile, stride):
    """Tile start offsets along one axis, final tile clamped flush to the edge."""
    if tile > total:
        raise GeometryError(f"tile ({tile}) larger than image ({total}) on this axis")
    pos, v = [], 0
    while True:
        if v + tile >= total:
            pos.append(total - tile)
            break
        pos.append(v)
        v += stride
    out = []
    for p in pos:                      # dedupe, preserve order
        if p not in out:
            out.append(p)
    return out


def _axis_positions_anchored(total, tile, stride, center):
    """Tile start offsets with one tile CENTERED on `center` (clamped to the
    frame), others laid outward at `stride`, outermost clamped flush.

    Mask chaining is safe for any position list whose consecutive gaps are
    <= stride (guaranteed here: outward gaps are exactly stride, and the
    edge-clamped insertions only shrink a gap)."""
    c = max(0, min(total - tile, center - tile // 2))
    positions = [c]
    p = c - stride
    while p > 0:
        positions.insert(0, p)
        p -= stride
    if positions[0] > 0:
        positions.insert(0, 0)
    p = c + stride
    while p + tile < total:
        positions.append(p)
        p += stride
    if positions[-1] + tile < total:
        positions.append(total - tile)
    out = []
    for q in positions:                # dedupe, preserve order
        if q not in out:
            out.append(q)
    return out


def _axis_positions_even_snapped(total, tile, stride, snap):
    """Even positions with every INTERMEDIATE position snapped to the `snap`
    grid (ref-grid exactness: a tile whose x/y is a whole number of reference
    cells slices its ref crop exactly instead of resampling). First position
    stays 0 and the last stays flush at total-tile -- coverage always wins
    over exactness at the frame edge. Returns None if snapping would break
    mask chaining (a gap > stride), so callers can widen the tile and retry."""
    base = _axis_positions_even(total, tile, stride)
    if snap <= 1 or len(base) <= 2:
        return base
    pos = [base[0]]
    for p in base[1:-1]:
        pos.append(min(total - tile, max(0, int(round(p / snap)) * snap)))
    pos.append(base[-1])
    out = []
    for p in pos:                       # dedupe, preserve order
        if p not in out:
            out.append(p)
    if any(out[i + 1] <= out[i] for i in range(len(out) - 1)):
        return None
    if any(out[i + 1] - out[i] > stride for i in range(len(out) - 1)):
        return None
    return out


def _axis_positions_even_hero(total, tile, border, snap, h0, h1):
    """Even positions nudged so mask-partition boundaries hug the hero
    interval [h0, h1) on this axis. A tile whose MASK falls fully inside
    the hero footprint on both axes is swallowed (skipped outright), so
    landing boundaries on the hero's edges converts partial overlaps into
    whole skipped tiles. Only positions the even layout was placing
    arbitrarily are moved; overlap conditioning and chaining rules are
    unchanged. Returns the best safe layout (ties -> most even)."""
    stride = tile - 2 * border
    base = _axis_positions_even_snapped(total, tile, stride, snap) \
        or _axis_positions_even(total, tile, stride)
    n = len(base)
    if n < 2 or h1 <= h0:
        return base
    TB = tile - border
    snap = max(1, snap)

    def bounds(pos):
        return [0] + [p + TB for p in pos[:-1]] + [total]

    def valid(pos):
        if pos[0] != 0 or pos[-1] != total - tile:
            return False
        return all(0 < b - a <= stride for a, b in zip(pos, pos[1:]))

    def score(pos):
        B = bounds(pos)
        swallowed = sum(1 for i in range(len(pos))
                        if B[i] >= h0 and B[i + 1] <= h1)
        gaps = [b - a for a, b in zip(pos, pos[1:])]
        mean = sum(gaps) / len(gaps)
        return (swallowed, -sum((g - mean) ** 2 for g in gaps))

    def respread(fixed):
        pos = [None] * n
        for k, v in fixed.items():
            pos[k] = v
        anchors = sorted(fixed)
        for a, b in zip(anchors, anchors[1:]):
            for j in range(1, b - a):
                v = pos[a] + (pos[b] - pos[a]) * j / (b - a)
                pos[a + j] = int(round(v / snap)) * snap
        return pos

    best, best_s = base, score(base)
    lo_need = h0 - TB                       # pos[i-1] >= this -> B_i >= h0
    hi_need = h1 - TB                       # pos[j]  <= this -> B_j+1 <= h1
    for i in range(n):                      # first swallowed cell
        for k in range(1, min(3, n - i) + 1):   # cells swallowed on this axis
            j = i + k - 1                   # last swallowed cell
            fixed = {0: 0, n - 1: total - tile}
            if i == 0:
                if h0 > 0:
                    continue
            elif i - 1 == 0:
                if 0 < lo_need:
                    continue
            else:
                v = max(base[i - 1], -((-lo_need) // snap) * snap)  # snap up
                if not (0 <= v <= total - tile):
                    continue
                fixed[i - 1] = v
            if j == n - 1:
                if h1 < total:
                    continue
            elif j >= n - 1:
                continue
            elif j == 0:
                if 0 > hi_need:
                    continue
            else:
                v = min(base[j], (hi_need // snap) * snap)          # snap down
                if not (0 <= v <= total - tile):
                    continue
                if j in fixed and fixed[j] != v:
                    continue
                fixed[j] = v
            if any(fixed[a] >= fixed[b] for a, b in
                   zip(sorted(fixed), sorted(fixed)[1:])):
                continue
            pos = respread(fixed)
            out = []
            for p in pos:                   # dedupe defensively
                if p not in out:
                    out.append(p)
            if len(out) == n and valid(out):
                s = score(out)
                if s > best_s:
                    best, best_s = out, s
    return best


def auto_tile_axis(total, cap, border, snap=1):
    """Smallest tile count first, then smallest tile, for one axis.

    All values in SOLVER UNITS (patch units -- same space axis_plan works
    in). Returns (tile, positions) with tile <= cap, tile a multiple of
    `snap` (>=1), and positions evenly spread and snap-aligned where
    possible. The minimal count is n = ceil((total-2b)/(cap-2b)); the tile
    is then the smallest snap-multiple whose n-tile even layout still
    chains masks safely after position snapping (widened one unit at a
    time if snapping eats the slack; n bumps only if the cap is hit).
    """
    snap = max(1, snap)
    if cap >= total:
        # single tile covers the axis; if that leaves it off the snap grid,
        # the crop is the WHOLE ref anyway, which is exact by definition
        return total, [0]
    b2 = 2 * border
    if cap - b2 <= 0:
        raise GeometryError(
            f"tile cap {cap} too small for context border {border} "
            f"(stride would be {cap - b2})")
    n = -((total - b2) // -(cap - b2))            # minimal tile count
    need = -((total + (n - 1) * b2) // -n)        # minimal even-coverage tile
    s0 = -(need // -snap) * snap                  # round up to snap grid
    # Widening the tile is the only lever that helps the snapped layout
    # (position count derives from stride, not from a requested n), so scan
    # sizes from minimal to the cap and take the first that chains safely.
    for s in range(s0, cap + 1, snap):
        pos = _axis_positions_even_snapped(total, s, s - b2, snap)
        if pos is not None:
            return s, pos
    # No snap-aligned layout fits under the cap: keep the minimal-count
    # even layout and let per-tile crop warnings flag any resampled refs.
    s = min(cap, s0) if s0 > b2 else need
    return s, _axis_positions_even(total, s, s - b2)


def _axis_positions_even(total, tile, stride):
    """Minimal tile count, evenly spread.

    n is the smallest count whose masks can partition the axis (each tile
    past the first contributes at most `stride` of new mask), and positions
    interpolate evenly between flush-left and flush-right. Consecutive gaps
    are <= stride by construction (the even gap is (total-tile)/(n-1) <=
    stride, and integer rounding cannot push a gap past stride because
    stride itself is an integer bound on the ceiling), so mask chaining is
    safe. Compared to flush placement this spreads the overlap across every
    joint instead of piling it into one heavily-overlapped final tile, and
    compared to anchored placement it never inserts edge-clamp extras."""
    if tile >= total:
        return [total - tile] if tile == total else [max(0, total - tile)]
    n = -((total - tile) // -stride) + 1          # ceil div + 1
    span = total - tile
    positions = [round(i * span / (n - 1)) for i in range(n)]
    for i in range(n - 2, -1, -1):                # enforce gap <= stride
        positions[i] = max(positions[i], positions[i + 1] - stride)
    positions[0] = 0
    out = []
    for p in positions:
        if p not in out:
            out.append(p)
    return out


def axis_plan(total, tile, border, anchor=None, placement="flush", pos_snap=1,
              hero=None):
    """
    Returns [(tile_start, mask_start_within_tile, mask_end_within_tile), ...]

    All values in latent cells. mask_* are relative to the tile origin, so
    they can be used directly to slice the extracted window. `anchor` (cell
    coordinate, optional) centers one tile on that point and lays the rest
    outward, so partition boundaries land as far from the anchor as possible.
    placement="even" ignores the anchor for POSITIONS (minimal count, evenly
    spread) -- callers that use an anchor for processing ORDER keep it.
    pos_snap > 1 (even placement only) snaps intermediate positions to that
    grid when it can do so without breaking mask chaining -- used to land
    tile origins on whole reference cells so ref crops slice exactly.
    """
    stride = tile - 2 * border
    if stride <= 0:
        raise GeometryError(
            f"border {border} too large for tile {tile}: stride would be {stride}"
        )
    if tile > total:
        raise GeometryError(f"tile ({tile}) larger than image ({total})")
    if placement == "even":
        if hero is not None:
            positions = _axis_positions_even_hero(total, tile, border,
                                                  pos_snap, hero[0], hero[1])
        else:
            positions = None
            if pos_snap > 1:
                positions = _axis_positions_even_snapped(total, tile, stride,
                                                         pos_snap)
            if positions is None:
                positions = _axis_positions_even(total, tile, stride)
    elif anchor is None:
        positions = _axis_positions(total, tile, stride)
    else:
        positions = _axis_positions_anchored(total, tile, stride, anchor)

    plan, gen_start = [], 0
    last = len(positions) - 1
    for i, p in enumerate(positions):
        # last tile must run to the edge; others stop a border short
        gen_end = total if i == last else p + tile - border
        ms, me = gen_start - p, gen_end - p
        if ms < 0 or me > tile or ms >= me:
            raise GeometryError(
                f"degenerate mask on tile {i} at {p}: [{ms}, {me}) within tile of {tile}"
            )
        # "clamped" = pulled off the uniform stride (flush edge insertions).
        # These are the tiles a naive fixed-border rule would double-generate.
        # Even placement spreads a little overlap everywhere by design, so
        # only a markedly narrowed gap (> 1 cell off stride) is flagged.
        if placement == "even":
            clamped = ((i > 0 and positions[i] - positions[i - 1] < stride - 1)
                       or (i < last and positions[i + 1] - p < stride - 1))
        elif anchor is None:
            clamped = p != i * stride
        else:
            clamped = ((i > 0 and p - positions[i - 1] < stride)
                       or (i < last and positions[i + 1] - p < stride))
        plan.append((p, ms, me, clamped))
        gen_start = gen_end
    return plan


def build_plan(width_px, height_px, tile_w_px, tile_h_px, border_px,
               order="raster", cell=DEFAULT_CELL, temporal=DEFAULT_TEMPORAL,
               patch=1, anchor_x_px=-1, anchor_y_px=-1, placement="flush",
               pos_snap_px=0, hero_rect_px=None):
    """
    Full 2D tile plan. Pixel values in, cell values out.

    Raises GeometryError with an actionable message if anything is off-grid,
    rather than silently rounding -- silent rounding is how you end up with a
    16px offset that only shows as a soft band 25 tiles later.
    """
    # The whole plan is solved in PATCH units, not latent cells.
    #
    # A DiT computes one update per patch of latent cells. If a mask boundary
    # falls inside a patch, the model produces a single result for that patch
    # while the sampler's per-cell mask keeps half of it and reverts the other
    # half -- a hard discontinuity at every boundary, on the patch grid. That
    # reads as aliasing / stair-stepping along tile edges, and no amount of
    # feathering fixes it because the granularity is the patch, not the cell.
    #
    # Solving in patch units makes every boundary patch-aligned by
    # construction, then scaling the result by `patch` expresses it back in
    # latent cells. With patch=1 (LTX: the VAE does all the compression, the
    # patchifier is 1x1x1) this is bit-identical to solving in cells.
    unit = cell * patch
    for name, v in (("width", width_px), ("height", height_px),
                    ("tile_width", tile_w_px), ("tile_height", tile_h_px),
                    ("context_border", border_px)):
        if v % unit:
            lo = (v // unit) * unit
            extra = f" (cell {cell} x patch {patch})" if patch > 1 else ""
            raise GeometryError(
                f"{name}={v} is not a multiple of {unit}{extra} "
                f"({v / unit:.4f} units). Use {lo} or {lo + unit}."
            )

    W, H = width_px // unit, height_px // unit
    TW, TH = tile_w_px // unit, tile_h_px // unit
    B = border_px // unit

    anchored = anchor_x_px >= 0 and anchor_y_px >= 0
    ax_u = int(round(anchor_x_px / unit)) if anchored else None
    ay_u = int(round(anchor_y_px / unit)) if anchored else None
    snap_u = (pos_snap_px // unit) if (pos_snap_px > 0
                                       and pos_snap_px % unit == 0) else 1
    hero_x = hero_y = None
    if hero_rect_px is not None:
        hx0, hy0, hx1, hy1 = hero_rect_px
        # conservative: shrink to whole units, so "inside the hero" in the
        # solver is never optimistic about swallowing
        hero_x = (-((-hx0) // unit), hx1 // unit)
        hero_y = (-((-hy0) // unit), hy1 // unit)
    cols = axis_plan(W, TW, B, anchor=ax_u, placement=placement,
                     pos_snap=snap_u, hero=hero_x)
    rows = axis_plan(H, TH, B, anchor=ay_u, placement=placement,
                     pos_snap=snap_u, hero=hero_y)

    p = patch                     # units -> latent cells
    if order == "anchor_out" and not anchored:
        order = "raster"          # anchor_out is meaningless without an anchor
    tiles, idx = [], 0
    for r, (y, my0, my1, cy) in enumerate(rows):
        seq = cols if (order != "serpentine" or r % 2 == 0) else list(reversed(cols))
        for (x, mx0, mx1, cx) in seq:
            tiles.append({
                "index": idx, "row": r,
                "x": x * p, "y": y * p, "w": TW * p, "h": TH * p,
                "mx0": mx0 * p, "mx1": mx1 * p, "my0": my0 * p, "my1": my1 * p,
                "clamped": bool(cx or cy),
                # pixel-space equivalents, for logging / sanity checks only
                "px": x * unit, "py": y * unit,
                "pmx0": mx0 * unit, "pmx1": mx1 * unit,
                "pmy0": my0 * unit, "pmy1": my1 * unit,
            })
            idx += 1

    if order == "anchor_out":
        # Process the anchor tile FIRST, then outward by distance, so every
        # later tile's context border carries already-refined content that
        # radiates from the anchor (the face) instead of from the top-left
        # corner. Coverage is unaffected: masks partition by position, and
        # disjoint masks paste correctly in any order.
        axc, ayc = ax_u * p, ay_u * p          # anchor in latent cells
        def _dist(t):
            cx = t["x"] + (t["mx0"] + t["mx1"]) / 2.0
            cy = t["y"] + (t["my0"] + t["my1"]) / 2.0
            return (cx - axc) ** 2 + (cy - ayc) ** 2
        tiles.sort(key=_dist)
        for i, t in enumerate(tiles):
            t["index"] = i

    return {
        "cell": cell,
        "patch": patch,
        "unit": unit,
        "placement": placement,
        "pos_snap_px": pos_snap_px if snap_u > 1 else 0,
        "temporal": temporal,
        "grid": (len(cols), len(rows)),
        "count": len(tiles),
        "latent_size": (W * p, H * p),
        "tile_cells": (TW * p, TH * p),
        "border_cells": B * p,
        "stride_cells": ((TW - 2 * B) * p, (TH - 2 * B) * p),
        "order": order,
        "anchor": (anchor_x_px, anchor_y_px) if anchored else None,
        "tiles": tiles,
    }


def format_plan(plan):
    """Human-readable plan. Print this before committing GPU hours to it."""
    W, H = plan["latent_size"]
    TW, TH = plan["tile_cells"]
    SW, SH = plan["stride_cells"]
    cell = plan["cell"]
    L = [
        f"latent      {W} x {H} cells  ({W * cell} x {H * cell} px)  cell={cell}",
        f"tile        {TW} x {TH} cells  ({TW * cell} x {TH * cell} px)",
        f"border      {plan['border_cells']} cells  ({plan['border_cells'] * cell} px)",
        f"stride      {SW} x {SH} cells  ({SW * cell} x {SH * cell} px)",
        f"grid        {plan['grid'][0]} x {plan['grid'][1]} = {plan['count']} tiles ({plan['order']})",
        "",
        f"{'idx':>3} {'cell x,y':>10} {'mask cells':>16} {'mask px (w x h)':>18}",
        "-" * 52,
    ]
    for t in plan["tiles"]:
        mc = f"[{t['mx0']}:{t['mx1']}] [{t['my0']}:{t['my1']}]"
        mp = f"{(t['mx1'] - t['mx0']) * cell} x {(t['my1'] - t['my0']) * cell}"
        xy = f"{t['x']},{t['y']}"
        L.append(f"{t['index']:>3} {xy:>10} {mc:>16} {mp:>18}")
    return "\n".join(L)


def verify_coverage(plan):
    """
    Assert every cell is generated exactly once. Cheap, and catches an entire
    class of geometry bug before it costs an hour of sampling.
    """
    W, H = plan["latent_size"]
    hits = [[0] * W for _ in range(H)]
    for t in plan["tiles"]:
        for yy in range(t["y"] + t["my0"], t["y"] + t["my1"]):
            row = hits[yy]
            for xx in range(t["x"] + t["mx0"], t["x"] + t["mx1"]):
                row[xx] += 1
    flat = [c for row in hits for c in row]
    return {
        "ok": all(c == 1 for c in flat),
        "never": sum(1 for c in flat if c == 0),
        "twice_or_more": sum(1 for c in flat if c > 1),
        "total": len(flat),
    }
